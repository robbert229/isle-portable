struct IDirect3D3;
struct IDirect3DDevice3 : public IDirect3DDevice2 {
	virtual HRESULT GetDirect3D(IDirect3D3** d3d) = 0;
	virtual HRESULT SetCurrentViewport(IDirect3DViewport3* viewport) = 0;
	virtual HRESULT GetRenderState(D3DRENDERSTATETYPE state, LPDWORD value) = 0;
	virtual HRESULT SetRenderState(D3DRENDERSTATETYPE state, DWORD value) = 0;
	virtual HRESULT GetLightState(D3DLIGHTSTATETYPE state, LPDWORD value) = 0;
	virtual HRESULT SetLightState(D3DLIGHTSTATETYPE state, DWORD value) = 0;
	virtual HRESULT SetTransform(D3DTRANSFORMSTATETYPE state, LPD3DMATRIX matrix) = 0;
	virtual HRESULT GetTransform(D3DTRANSFORMSTATETYPE state, LPD3DMATRIX matrix) = 0;
	virtual HRESULT DrawIndexedPrimitive(
		D3DPRIMITIVETYPE primitiveType,
		DWORD vertexType,
		LPVOID vertices,
		DWORD vertexCount,
		WORD* indices,
		DWORD indexCount,
		DWORD flags
	) = 0;
	virtual HRESULT GetTexture(DWORD stage, IDirect3DTexture2** texture) = 0;
	virtual HRESULT SetTexture(DWORD stage, IDirect3DTexture2* texture) = 0;
	virtual HRESULT GetTextureStageState(DWORD stage, D3DTEXTURESTAGESTATETYPE state, LPDWORD value) = 0;
	virtual HRESULT SetTextureStageState(DWORD stage, D3DTEXTURESTAGESTATETYPE state, DWORD value) = 0;
};
typedef IDirect3DDevice3* LPDIRECT3DDEVICE3;

